# Generate the headline statement from ALL THREE headline estimates (complete case, multiple imputation,
# missing-indicator) and write it, identically, to:
#   site/public/data/headline.json (used by the site), and the generated blocks in README.md,
#   docs/methods.md and PROGRESS.md (between HEADLINE:START / HEADLINE:END markers).
# analysis/tests/testthat/test-headline.R regenerates the block and fails if any document disagrees.
source("analysis/R/config.R")
source("analysis/R/export_utils.R")

evalue_rr <- function(rr) { r <- ifelse(rr < 1, 1 / rr, rr); r + sqrt(r * (r - 1)) }
evalue_ci <- function(est, lcl, ucl) if (lcl <= 1 && ucl >= 1) 1 else evalue_rr(if (est >= 1) lcl else ucl)
f2 <- function(x) sprintf("%.2f", x)
est_str <- function(r) sprintf("OR %s (95%% CI %s–%s)", f2(r$or), f2(r$lcl), f2(r$ucl))
ev_str <- function(r) sprintf("E-value %s (CI bound %s)", f2(evalue_rr(r$or)), f2(evalue_ci(r$or, r$lcl, r$ucl)))

START <- "<!-- HEADLINE:START (generated by analysis/R/headline.R from the model outputs; do not edit by hand) -->"
END <- "<!-- HEADLINE:END -->"

build_headline <- function() {
  rd <- function(f) jsonlite::fromJSON(root_path("site", "public", "data", f))$data
  grid <- rd("models_grid.json"); pir <- rd("models_pir.json"); mi <- rd("models_mi.json")
  g <- function(b) grid[grid$exposure == "x_ever" & grid$outcome == "cancer_any" & grid$sample == "main" & grid$blocks == b, ]
  cc <- g("demo+tobacco+alcohol+ses"); demo <- g("demo")
  mii <- pir[pir$exposure == "x_ever" & pir$outcome == "cancer_any" & pir$approach == "missing_category", ]
  mim <- mi[mi$exposure == "x_ever" & mi$outcome == "cancer_any", ]
  spec <- grid[grid$outcome == "cancer_any", ]
  ests <- list(cc, mim, mii)
  lo <- round(min(sapply(ests, `[[`, "or")), 1); hi <- round(max(sapply(ests, `[[`, "or")), 1)
  range_txt <- if (lo == hi) sprintf("OR ~%.1f", lo) else sprintf("OR ~%.1f–%.1f", lo, hi)
  statement <- sprintf(paste0("Among U.S. adults aged 20–59 (NHANES 2005–2018), ever-use of cannabis shows a modest association with ",
    "self-reported cancer (%s) that is attenuated by smoking adjustment and not robust across analytic choices."), range_txt)
  n_excl <- sum(spec$lcl > 1 | spec$ucl < 1)
  items <- c(
    sprintf("Complete case (main analysis; n = %s, %d cases): %s; %s", format(cc$n, big.mark = ","), cc$cases, est_str(cc), ev_str(cc)),
    sprintf("Multiple imputation (m = %d; n = %s, %d cases): %s; %s", mim$m, format(mim$n, big.mark = ","), mim$cases, est_str(mim), ev_str(mim)),
    sprintf("Missing-indicator category for income (n = %s, %d cases): %s; %s", format(mii$n, big.mark = ","), mii$cases, est_str(mii), ev_str(mii)),
    sprintf("Before smoking adjustment (demographics only): %s", est_str(demo)),
    sprintf("Across all %d specifications for any cancer, ORs range %s–%s and %d of %d confidence intervals exclude 1.",
            nrow(spec), f2(min(spec$or)), f2(max(spec$or)), n_excl, nrow(spec)))
  block <- paste(c(START, "", paste0("**Headline.** ", statement), "",
                   paste0("- ", items), "",
                   "All models: ever-use vs never-use, any self-reported cancer, adjusted for demographics, smoking, alcohol and socioeconomic factors (except the demographics-only line). E-values treat the OR as a risk ratio (cancer history ≈5%).",
                   "", END), collapse = "\n")
  list(statement = statement, range = range_txt, block = block,
       estimates = list(
         complete_case = c(cc[c("or", "lcl", "ucl", "n", "cases")], list(evalue = evalue_rr(cc$or), evalue_ci = evalue_ci(cc$or, cc$lcl, cc$ucl))),
         multiple_imputation = c(mim[c("or", "lcl", "ucl", "n", "cases", "m", "fmi")], list(evalue = evalue_rr(mim$or), evalue_ci = evalue_ci(mim$or, mim$lcl, mim$ucl))),
         missing_indicator = c(mii[c("or", "lcl", "ucl", "n", "cases")], list(evalue = evalue_rr(mii$or), evalue_ci = evalue_ci(mii$or, mii$lcl, mii$ucl))),
         demographics_only = as.list(demo[c("or", "lcl", "ucl")])),
       spec = list(n = nrow(spec), min = min(spec$or), max = max(spec$or), n_ci_excludes_1 = n_excl))
}

HEADLINE_DOCS <- c("README.md", "docs/methods.md", "PROGRESS.md")

extract_block <- function(txt) {
  i <- regexpr(START, txt, fixed = TRUE); j <- regexpr(END, txt, fixed = TRUE)
  if (i < 0 || j < 0) return(NA_character_)
  substr(txt, i, j + attr(j, "match.length") - 1)
}

if (sys.nframe() == 0) {
  h <- build_headline()
  for (f in HEADLINE_DOCS) {
    p <- root_path(f); txt <- paste(readLines(p, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
    old <- extract_block(txt)
    if (is.na(old)) stop("No HEADLINE markers in ", f)
    txt <- sub(old, h$block, txt, fixed = TRUE)
    writeLines(txt, p, useBytes = TRUE)
  }
  write_site_json(list(statement = h$statement, range = h$range, estimates = h$estimates, spec = h$spec), "headline.json",
                  list(note = "Generated by analysis/R/headline.R from models_grid.json, models_mi.json and models_pir.json."))
  message(h$statement)
}
