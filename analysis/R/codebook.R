# Parse CDC codebook HTML into tidy tables:
#   data/derived/codebook_vars.csv   (file, cycle, variable, label, target)
#   data/derived/codebook_values.csv (file, cycle, variable, code, description, count, skip_to)
# Also writes docs/variables.md (availability matrix of key variables by cycle).
source("analysis/R/config.R")
suppressMessages({ library(xml2) })

parse_codebook <- function(path) {
  doc <- read_html(path, encoding = "latin1")
  hs <- xml_find_all(doc, "//h3[@class='vartitle']")
  vars <- list(); vals <- list()
  fname <- sub("\\.htm$", "", basename(path))
  cyc <- sub(".*_", "", fname)
  for (h in hs) {
    v <- xml_attr(h, "id")
    dl <- xml_find_first(h, "following-sibling::dl[1]")
    dts <- trimws(xml_text(xml_find_all(dl, "./dt")))
    dds <- trimws(gsub("\\s+", " ", xml_text(xml_find_all(dl, "./dd"))))
    get <- function(k) { i <- grep(k, dts, fixed = TRUE); if (length(i)) dds[i[1]] else NA_character_ }
    vars[[length(vars) + 1]] <- data.frame(file = fname, cycle = cyc, variable = toupper(v),
      label = get("SAS Label"), target = get("Target"), stringsAsFactors = FALSE)
    tb <- xml_find_first(h, "following-sibling::table[1]")
    # make sure the table belongs to this variable (next h3 must come after it)
    if (!inherits(tb, "xml_missing")) {
      nxt <- xml_find_first(h, "following-sibling::h3[1]")
      tb_prev_h3 <- xml_find_first(tb, "preceding-sibling::h3[1]")
      if (identical(xml_attr(tb_prev_h3, "id"), v)) {
        trs <- xml_find_all(tb, ".//tbody/tr")
        for (tr in trs) {
          td <- trimws(gsub("\\s+", " ", xml_text(xml_find_all(tr, "./td"))))
          if (length(td) >= 3) vals[[length(vals) + 1]] <- data.frame(
            file = fname, cycle = cyc, variable = toupper(v), code = td[1], description = td[2],
            count = suppressWarnings(as.integer(gsub(",", "", td[3]))),
            skip_to = if (length(td) >= 5) td[5] else NA_character_, stringsAsFactors = FALSE)
        }
      }
    }
  }
  list(vars = do.call(rbind, vars), vals = if (length(vals)) do.call(rbind, vals) else NULL)
}

if (sys.nframe() == 0) {
  cb <- list.files(root_path("data", "raw", "codebooks"), "\\.htm$", full.names = TRUE)
  parsed <- lapply(cb, parse_codebook)
  vars <- do.call(rbind, lapply(parsed, `[[`, "vars"))
  vals <- do.call(rbind, lapply(parsed, `[[`, "vals"))
  dir.create(root_path("data", "derived"), showWarnings = FALSE)
  write.csv(vars, root_path("data", "derived", "codebook_vars.csv"), row.names = FALSE)
  write.csv(vals, root_path("data", "derived", "codebook_values.csv"), row.names = FALSE)

  key <- list(
    "Demographics" = c("RIDAGEYR","RIAGENDR","RIDRETH1","RIDRETH3","DMDEDUC2","INDFMPIR","RIDEXPRG","WTMEC2YR","SDMVSTRA","SDMVPSU"),
    "Marijuana (DUQ)" = c("DUQ200","DUQ210","DUQ211","DUQ213","DUQ215Q","DUQ215U","DUQ217","DUQ219","DUQ220Q","DUQ220U","DUQ230"),
    "Tobacco (SMQ)" = c("SMQ020","SMQ040","SMD030","SMQ050Q","SMD641","SMD650","SMQ900","SMQ905"),
    "Cancer (MCQ)" = c("MCQ220","MCQ230A","MCQ230B","MCQ230C","MCQ230D","MCQ240A","MCQ240F","MCQ240N","MCD240A","MCD240B","MCD240C"),
    "Alcohol (ALQ)" = c("ALQ101","ALQ110","ALQ111","ALQ120Q","ALQ120U","ALQ121","ALQ130","ALQ141Q","ALQ142","ALQ151"),
    "Insurance (HIQ)" = c("HIQ011"),
    "Body measures (BMX)" = c("BMXBMI"),
    "Sexual behavior (SXQ)" = c("SXD021","SXD031","SXD101","SXD171","SXQ753","SXQ265"),
    "HPV oral rinse (ORHPV)" = c("ORXHPV","ORXH16","ORXH18"),
    "HPV vaginal swab (HPVSWR)" = c("LBDRPCR","LBDR16","LBDR18","LBXHP2C"),
    "HPV serum (HPVSRM)" = c("LBXPV16","LBXPV18"))
  sfx <- CYCLES$suffix
  lines <- c("# Variable availability by NHANES cycle",
    "",
    "Generated by `analysis/R/codebook.R` from the CDC codebook HTML files listed in `data/raw/MANIFEST.csv`.",
    "✓ = variable present in that cycle's public file; – = absent (or file not public).",
    "",
    "Cycles: D = 2005–2006, E = 2007–2008, F = 2009–2010, G = 2011–2012, H = 2013–2014, I = 2015–2016, J = 2017–2018.",
    "")
  for (blk in names(key)) {
    lines <- c(lines, paste0("## ", blk), "",
      paste0("| Variable | Label (latest cycle) | ", paste(sfx, collapse = " | "), " |"),
      paste0("|---|---|", paste(rep("---", length(sfx)), collapse = "|"), "|"))
    for (v in key[[blk]]) {
      have <- vars[vars$variable == v, ]
      lab <- if (nrow(have)) have$label[nrow(have)] else ""
      marks <- vapply(sfx, function(s) if (s %in% have$cycle) "✓" else "–", "")
      lines <- c(lines, paste0("| `", v, "` | ", lab, " | ", paste(marks, collapse = " | "), " |"))
    }
    lines <- c(lines, "")
  }
  # Target (eligible age) of DUQ200 per cycle
  t200 <- vars[vars$variable == "DUQ200", c("cycle", "target")]
  lines <- c(lines, "## Target population of DUQ200 (codebook 'Target' field)", "",
             "| Cycle | Target |", "|---|---|",
             paste0("| ", t200$cycle, " | ", t200$target, " |"), "",
             "Note: although several DUQ documentation pages describe public data for ages 18–69,",
             "in the public files every participant aged 60–69 is missing DUQ200 (verified in",
             "`analysis/tests/testthat/test-harmonize.R`). Marijuana analyses are restricted to ≤59.", "")
  writeLines(lines, root_path("docs", "variables.md"))
  message("Parsed ", length(cb), " codebooks; ", nrow(vars), " variables; wrote docs/variables.md")
}
